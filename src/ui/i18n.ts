export const STRINGS: Record<Lang, Record<StringKey, string>> = { zh, en };

export type Translator = (key: StringKey, params?: Record<string, string | number>) => string;

// makeT("en")("errorCount", { n: 2 }) → "2 to review"
export function makeT(lang: Lang): Translator {
  const dict = STRINGS[lang] ?? STRINGS.zh;
  return (key, params) => {
    const template = dict[key] ?? key;
    if (!params) return template;
    return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
      name in params ? String(params[name]) : whole,
    );
  };
}

// 时间显示按语言：侧栏日期「9月30日」/「Sep 30」。
export function formatDate(value: string, lang: Lang): string {
  return new Intl.DateTimeFormat(lang === "en" ? "en-US" : "zh-CN", {
    month: "short",
    day: "numeric",
  }).format(new Date(value));
}

// About 弹窗的构建时间。
export function formatBuildTime(value: string, lang: Lang): string {
  return new Date(value).toLocaleString(lang === "en" ? "en-US" : "zh-CN", { hour12: false });
}
